<?php
// CampusCred - 1-Click Automated Web Installer & Database Configuration Wizard
// Specially optimized for InfinityFree, cPanel, and Shared Web Hosting
session_start();

$configFile = __DIR__ . '/config.php';
$isInstalled = false;
$configPermissionWarning = false;
$generatedConfigCode = '';

// Support direct 1-click download of generated config.php if host prevents writing
if (isset($_GET['action']) && $_GET['action'] === 'download_config' && !empty($_SESSION['generated_config'])) {
    header('Content-Type: application/x-httpd-php');
    header('Content-Disposition: attachment; filename="config.php"');
    echo $_SESSION['generated_config'];
    exit;
}

// Only check existing working connection on GET requests (never on POST)
if ($_SERVER['REQUEST_METHOD'] !== 'POST' && file_exists($configFile)) {
    // Read config file to check if it has non-localhost DB_HOST
    $rawConfig = @file_get_contents($configFile);
    if ($rawConfig && preg_match("/define\('DB_HOST',\s*'([^']+)'\)/", $rawConfig, $mHost)) {
        $existingHost = $mHost[1];
        if ($existingHost !== '127.0.0.1' && $existingHost !== 'localhost') {
            preg_match("/define\('DB_NAME',\s*'([^']+)'\)/", $rawConfig, $mName);
            preg_match("/define\('DB_USER',\s*'([^']+)'\)/", $rawConfig, $mUser);
            preg_match("/define\('DB_PASS',\s*'([^']*)'\)/", $rawConfig, $mPass);

            if (!empty($mName[1]) && !empty($mUser[1])) {
                try {
                    $testPdo = new PDO(
                        'mysql:host=' . $existingHost . ';dbname=' . $mName[1] . ';charset=utf8mb4',
                        $mUser[1],
                        $mPass[1] ?? '',
                        [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION, PDO::ATTR_TIMEOUT => 2]
                    );
                    $checkTables = $testPdo->query("SHOW TABLES LIKE 'users'")->fetch();
                    if ($checkTables) {
                        $isInstalled = true;
                    }
                } catch (Throwable $t) {
                    $isInstalled = false;
                }
            }
        }
    }
}

$error = '';
$success = false;

if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['action']) && $_POST['action'] === 'install') {
    $db_host = trim($_POST['db_host'] ?? '');
    $db_name = trim($_POST['db_name'] ?? '');
    $db_user = trim($_POST['db_user'] ?? '');
    $db_pass = (string)($_POST['db_pass'] ?? '');
    $college_name = trim($_POST['college_name'] ?? 'Swami Keshvanand Institute of Technology, Management & Gramothan');
    $college_short = trim($_POST['college_short'] ?? 'SKIT Jaipur');

    if ($db_host === '' || $db_name === '' || $db_user === '') {
        $error = 'Database Host, Database Name, and Database User are required fields.';
    } else {
        try {
            // 1. Establish direct PDO connection to verify credentials
            $pdo = new PDO(
                "mysql:host={$db_host};dbname={$db_name};charset=utf8mb4",
                $db_user,
                $db_pass,
                [
                    PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                    PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
                    PDO::ATTR_EMULATE_PREPARES => false,
                    PDO::ATTR_TIMEOUT => 6
                ]
            );

            // 2. Provision database schema and seed demo accounts using active PDO
            require_once __DIR__ . '/db.php';
            if (function_exists('initialize_database_tables')) {
                initialize_database_tables($pdo);
            }

            // 3. Prepare updated config.php code
            $configContent = "<?php\n"
                . "// CampusCred - Configuration File\n"
                . "// Generated by Web Installer on " . date('Y-m-d H:i:s') . "\n\n"
                . "// 1. Database Connection Parameters\n"
                . "define('DB_HOST', " . var_export($db_host, true) . ");\n"
                . "define('DB_NAME', " . var_export($db_name, true) . ");\n"
                . "define('DB_USER', " . var_export($db_user, true) . ");\n"
                . "define('DB_PASS', " . var_export($db_pass, true) . ");\n\n"
                . "// 2. Institutional Branding\n"
                . "define('COLLEGE_NAME', " . var_export($college_name, true) . ");\n"
                . "define('COLLEGE_SHORT_NAME', " . var_export($college_short, true) . ");\n"
                . "define('PROJECT_CODE', 'SKIT021');\n"
                . "define('APP_NAME', 'CampusCred · Student Participation & Achievement Management System');\n"
                . "define('APP_TAGLINE', 'Centralized Digital Repository, Recruiter Talent Portal & Tamper-Evident Verification');\n"
                . "define('ORG_TYPE_LABEL', 'Institution');\n\n"
                . "// 3. Security & Uploads\n"
                . "define('UPLOAD_DIR', __DIR__ . '/uploads');\n"
                . "define('MAX_UPLOAD_BYTES', 5 * 1024 * 1024); // 5 MB\n"
                . "define('ALLOWED_MIME_TYPES', [\n"
                . "    'application/pdf' => 'pdf',\n"
                . "    'image/jpeg'      => 'jpg',\n"
                . "    'image/png'       => 'png',\n"
                . "]);\n\n"
                . "// 4. Feature Flags\n"
                . "define('ENABLE_RECRUITER_PORTAL', true);\n"
                . "define('ENABLE_PUBLIC_VERIFICATION', true);\n"
                . "define('ENABLE_PUBLIC_TALENT_DIRECTORY', true);\n\n"
                . "// 5. Base URL helper - Dynamically auto-detects subfolder or root domain\n"
                . "if (!defined('BASE_URL')) {\n"
                . "    \$envBase = getenv('BASE_URL');\n"
                . "    if (\$envBase !== false) {\n"
                . "        define('BASE_URL', rtrim(\$envBase, '/'));\n"
                . "    } else {\n"
                . "        \$scriptName = str_replace('\\\\', '/', \$_SERVER['SCRIPT_NAME'] ?? '');\n"
                . "        if (strpos(\$scriptName, '/campuscred') === 0) {\n"
                . "            define('BASE_URL', '/campuscred');\n"
                . "        } else {\n"
                . "            define('BASE_URL', '');\n"
                . "        }\n"
                . "    }\n"
                . "}\n";

            $generatedConfigCode = $configContent;
            $_SESSION['generated_config'] = $configContent;

            // 4. Try saving config.php to disk
            $written = @file_put_contents($configFile, $configContent);
            if ($written === false) {
                // Shared host file permissions prevented automatic overwrite
                $configPermissionWarning = true;
            }

            // 5. Ensure uploads directory exists
            if (!is_dir(__DIR__ . '/uploads')) {
                @mkdir(__DIR__ . '/uploads', 0777, true);
            }

            $success = true;
            $isInstalled = true;

        } catch (PDOException $ex) {
            $error = 'Database Connection Failed: ' . $ex->getMessage();
        } catch (Throwable $t) {
            $error = 'Installation Error: ' . $t->getMessage();
        }
    }
}
